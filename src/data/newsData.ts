const STORAGE_KEY = 'cfpitmc_news_articles_v5';

// Async sync helper
export async function syncNewsWithBackend(): Promise<NewsArticle[]> {
  try {
    const res = await fetch('/api/news');
    if (res.ok) {
      const data = await res.json();
      if (Array.isArray(data) && data.length > 0) {
        localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
        window.dispatchEvent(new Event('cfpitmc_news_updated'));
        return data;
      }
    }
  } catch (e) {
    console.warn('Backend news sync offline, using local cache');
  }
  return getStoredNews();
}

export function getStoredNews(): NewsArticle[] {
  if (typeof window === 'undefined') return INITIAL_NEWS_ARTICLES;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_NEWS_ARTICLES));
      // Trigger background sync
      setTimeout(() => syncNewsWithBackend(), 100);
      return INITIAL_NEWS_ARTICLES;
    }
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed) || parsed.length === 0) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_NEWS_ARTICLES));
      setTimeout(() => syncNewsWithBackend(), 100);
      return INITIAL_NEWS_ARTICLES;
    }
    return parsed;
  } catch (e) {
    console.error('Failed to load news articles from localStorage', e);
    return INITIAL_NEWS_ARTICLES;
  }
}

export function saveStoredNews(articles: NewsArticle[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(articles));
    window.dispatchEvent(new Event('cfpitmc_news_updated'));
  } catch (e) {
    console.error('Failed to save news articles to localStorage', e);
  }
}

export function createNewsArticle(article: Omit<NewsArticle, 'id' | 'viewsCount' | 'likesCount'>): NewsArticle {
  const current = getStoredNews();
  const newArticle: NewsArticle = {
    ...article,
    id: `news-${Date.now()}`,
    viewsCount: 0,
    likesCount: 0
  };
  const updated = [newArticle, ...current];
  saveStoredNews(updated);

  // Send to backend async
  fetch('/api/news', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(newArticle)
  }).then(r => r.json()).then(() => syncNewsWithBackend()).catch(() => {});

  return newArticle;
}

export function updateNewsArticle(id: string, updates: Partial<NewsArticle>): NewsArticle | null {
  const current = getStoredNews();
  const index = current.findIndex(a => a.id === id);
  if (index === -1) return null;
  const updatedArticle = { ...current[index], ...updates };
  current[index] = updatedArticle;
  saveStoredNews(current);

  // Send to backend async
  fetch(`/api/news/${id}`, {
    method: 'PUT',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(updates)
  }).catch(() => {});

  return updatedArticle;
}

export function deleteNewsArticle(id: string): boolean {
  const current = getStoredNews();
  const filtered = current.filter(a => a.id !== id);
  if (filtered.length === current.length) return false;
  saveStoredNews(filtered);

  fetch(`/api/news/${id}`, { method: 'DELETE' }).catch(() => {});

  return true;
}

export function resetNewsToDefault(): NewsArticle[] {
  saveStoredNews(INITIAL_NEWS_ARTICLES);
  fetch('/api/news/reset', { method: 'POST' }).then(() => syncNewsWithBackend()).catch(() => {});
  return INITIAL_NEWS_ARTICLES;
}
